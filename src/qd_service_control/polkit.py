"""The polkit rule that lets the tool's user run its unit jobs, from the YAML.

The rule is ES5 JavaScript (polkitd's mozjs). It handles only
``org.freedesktop.systemd1.manage-units`` for one user, allows the verbs the
control PVs use on an exact list of units (every service unit, template
instances in full, and every group unit), logs any other request from that
user and denies it, and leaves every other action and user to later rules.
"""

import json
from typing import Final

from qd_service_control.config.spec import StackSpec

ACTION: Final = "org.freedesktop.systemd1.manage-units"
VERBS: Final = ("start", "stop", "restart")


def _js(value: object) -> str:
    """A JavaScript literal: JSON with non-ASCII escaped (ES5 treats U+2028
    and U+2029 as line terminators inside string literals)."""
    return json.dumps(value, ensure_ascii=True)


def rule_units(spec: StackSpec) -> list[str]:
    """Every unit the tool may start, stop or restart, sorted."""
    units = {s.unit for s in spec.services.values()}
    units |= {g.unit for g in spec.groups.values()}
    return sorted(units)


def polkit_rule(spec: StackSpec, user: str) -> str:
    """The rule for ``user`` to run start/stop/restart jobs on the stack's units."""
    return f"""\
// Generated by qd-service-control generate-polkit for {spec.prefix}. Do not edit;
// regenerate it from the YAML instead.
polkit.addRule(function (action, subject) {{
    if (action.id !== {_js(ACTION)} || subject.user !== {_js(user)})
        return polkit.Result.NOT_HANDLED;
    var units = {_js(rule_units(spec))};
    var verbs = {_js(list(VERBS))};
    var unit = action.lookup("unit");
    var verb = action.lookup("verb");
    if (units.indexOf(unit) >= 0 && verbs.indexOf(verb) >= 0)
        return polkit.Result.YES;
    polkit.log("qd-service-control: denied " + subject.user + " unit=" + unit + " verb=" + verb);
    return polkit.Result.NO;
}});
"""
